/** Which stage of the seminar map a task is, from its name; -1 when it is none of them. */
export function stageIndexOf(taskTitle: string): number {
  const title = normaliseName(taskTitle);
  if (!title) return -1;
  const exact = SEMINAR_STAGES.findIndex((stage) => normaliseName(stage) === title);
  if (exact >= 0) return exact;
  // "פרק א׳" for "פרק א׳: כל הרקע התיאורטי": the part before the colon is enough.
  return SEMINAR_STAGES.findIndex((stage) => normaliseName(stage.split(':')[0]) === title);
}

/** The proposed lines for a task, or none when it is not a stage of the map. */
export function proposedRubricFor(taskTitle: string): readonly RubricLine[] {
  return PROPOSED_STAGE_RUBRICS[stageIndexOf(taskTitle)] ?? [];
}
